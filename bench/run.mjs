// Runs the browser benchmarks and writes results/results.json + results/RESULTS.md.
// Usage: npm run build && node run.mjs [--runs=3] [--quick]
import { createServer } from 'node:http'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright-core'

const here = path.dirname(fileURLToPath(import.meta.url))
const dist = path.join(here, 'dist')
const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const [k, v] = a.replace(/^--/, '').split('=')
    return [k, v ?? true]
  })
)
const quick = Boolean(args.quick)
const runs = Number(args.runs ?? (quick ? 1 : 3))

if (!existsSync(dist)) {
  console.error('dist/ not found. Run `npm run build` first.')
  process.exit(1)
}

const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css' }
const server = createServer(async (req, res) => {
  const url = new URL(req.url, 'http://localhost')
  const file = path.join(dist, url.pathname === '/' ? 'index.html' : url.pathname)
  if (!file.startsWith(dist)) {
    res.writeHead(403).end()
    return
  }
  try {
    const body = await readFile(file)
    res.writeHead(200, { 'content-type': MIME[path.extname(file)] ?? 'application/octet-stream' })
    res.end(body)
  } catch {
    res.writeHead(404).end()
  }
})
await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve))
const base = `http://127.0.0.1:${server.address().port}`

const browser = await chromium.launch({
  channel: 'chrome',
  headless: true,
  args: ['--enable-precise-memory-info', '--js-flags=--expose-gc', '--disable-background-timer-throttling'],
})

const configs = {
  readInHotPath: quick
    ? [{ seriesCount: 1, points: 50000, iterations: 30 }]
    : [
        { seriesCount: 1, points: 10000, iterations: 200 },
        { seriesCount: 1, points: 50000, iterations: 100 },
        { seriesCount: 1, points: 200000, iterations: 40 },
        { seriesCount: 1, points: 500000, iterations: 20 },
        { seriesCount: 4, points: 50000, iterations: 60 },
      ],
  overlayUpdate: quick
    ? [{ seriesCount: 1, points: 50000, iterations: 20 }]
    : [
        { seriesCount: 1, points: 10000, iterations: 100 },
        { seriesCount: 1, points: 200000, iterations: 40 },
        { seriesCount: 1, points: 500000, iterations: 20 },
      ],
  syncLoop: [{}],
  initialRender: quick
    ? [{ points: 50000, iterations: 3 }]
    : [
        { points: 50000, iterations: 5 },
        { points: 200000, iterations: 5 },
        { points: 500000, iterations: 3 },
      ],
}

const results = []
for (const v of ['v5', 'v6']) {
  for (const [scenario, list] of Object.entries(configs)) {
    for (const config of list) {
      const perRun = []
      for (let r = 0; r < runs; r++) {
        const page = await browser.newPage()
        await page.goto(`${base}/?v=${v}`)
        await page.waitForFunction(() => window.__ready === true)
        const echartsVersion = await page.evaluate(() => window.__bench.echartsVersion)
        const data = await page.evaluate(([s, c]) => window.__bench[s](c), [scenario, config])
        perRun.push({ echartsVersion, data })
        await page.close()
      }
      results.push({ version: v, echartsVersion: perRun[0].echartsVersion, scenario, config, runs: perRun.map((p) => p.data) })
      console.log(`done ${v} ${scenario} ${JSON.stringify(config)}`)
    }
  }
}

const chromeVersion = browser.version()
await browser.close()
server.close()

const env = {
  date: new Date().toISOString().slice(0, 10),
  os: `${os.type()} ${os.release()} (${os.arch()})`,
  cpu: os.cpus()[0]?.model?.trim(),
  cores: os.cpus().length,
  memoryGB: Math.round(os.totalmem() / 2 ** 30),
  node: process.version,
  chrome: chromeVersion,
  runsPerConfig: runs,
  quick,
}

await mkdir(path.join(here, 'results'), { recursive: true })
await writeFile(path.join(here, 'results', quick ? 'results.quick.json' : 'results.json'), JSON.stringify({ env, results }, null, 2))

// ---------- markdown ----------
const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b)
  return s[Math.floor(s.length / 2)]
}
const ms = (x) => (x >= 100 ? x.toFixed(0) : x >= 10 ? x.toFixed(1) : x >= 0.01 ? x.toFixed(2) : x >= 0.0005 ? x.toFixed(4) : '<0.001')
const kb = (b) => (b == null ? 'n/a' : b >= 1e6 ? `${(b / 1e6).toFixed(1)} MB` : `${Math.round(b / 1e3)} KB`)
const label = (c) => `${c.seriesCount ?? 1}×${(c.points / 1000).toFixed(0)}k`

const lines = []
lines.push(`# Results`, '')
lines.push(`Generated by \`bench/run.mjs\` on ${env.date}. Numbers are from one machine and are **reference values, not guarantees**.`, '')
lines.push('| | |', '|---|---|')
lines.push(`| OS | ${env.os} |`, `| CPU | ${env.cpu} (${env.cores} threads), ${env.memoryGB} GB RAM |`)
lines.push(`| Browser | headless Chrome ${env.chrome} |`, `| Node | ${env.node} |`)
lines.push(`| ECharts | 5.6.0 and 6.1.0 |`, `| Runs | ${env.runsPerConfig} fresh page loads per configuration; the table shows the median of per-run medians |`, '')

for (const v of ['v5', 'v6']) {
  const ver = v === 'v5' ? '5.6.0' : '6.1.0'
  lines.push(`## ECharts ${ver}`, '')

  const A = results.filter((r) => r.version === v && r.scenario === 'readInHotPath')
  if (A.length) {
    lines.push('### A. Reading chart state in a hot handler (ms per call, median / p95)', '')
    const names = Object.keys(A[0].runs[0])
    lines.push(`| variant | ${A.map((r) => label(r.config)).join(' | ')} |`, `|---|${A.map(() => '---').join('|')}|`)
    for (const n of names) {
      const cells = A.map((r) => `${ms(median(r.runs.map((d) => d[n].median)))} / ${ms(median(r.runs.map((d) => d[n].p95)))}`)
      lines.push(`| ${n} | ${cells.join(' | ')} |`)
    }
    lines.push('', 'Approximate allocation per call (heap growth after a forced GC):', '')
    lines.push(`| variant | ${A.map((r) => label(r.config)).join(' | ')} |`, `|---|${A.map(() => '---').join('|')}|`)
    for (const n of names) {
      const cells = A.map((r) => kb(median(r.runs.map((d) => d[n].allocBytesPerCall).filter((x) => x != null)) ?? null))
      lines.push(`| ${n} | ${cells.join(' | ')} |`)
    }
    lines.push('', 'Column label = series × points per series.', '')
  }

  const B = results.filter((r) => r.version === v && r.scenario === 'overlayUpdate')
  if (B.length) {
    lines.push('### B. Moving an overlay line (ms per update, median; "+paint" forces a synchronous canvas refresh)', '')
    const names = Object.keys(B[0].runs[0])
    lines.push(`| variant | ${B.map((r) => `${label(r.config)} update`).join(' | ')} | ${B.map((r) => `${label(r.config)} +paint`).join(' | ')} |`)
    lines.push(`|---|${[...B, ...B].map(() => '---').join('|')}|`)
    for (const n of names) {
      const u = B.map((r) => ms(median(r.runs.map((d) => d[n].updateOnly.median))))
      const p = B.map((r) => ms(median(r.runs.map((d) => d[n].updateAndPaint.median))))
      lines.push(`| ${n} | ${[...u, ...p].join(' | ')} |`)
    }
    lines.push('')
  }

  const C = results.filter((r) => r.version === v && r.scenario === 'syncLoop')
  if (C.length) {
    lines.push('### C. Two charts syncing dataZoom (events caused by one user zoom; cap = 400)', '')
    lines.push('| variant | events | hit cap |', '|---|---|---|')
    const d = C[0].runs[0]
    for (const [n, val] of Object.entries(d)) lines.push(`| ${n} | ${val.events} | ${val.capped ? 'yes' : 'no'} |`)
    lines.push('')
  }

  const D = results.filter((r) => r.version === v && r.scenario === 'initialRender')
  if (D.length) {
    lines.push('### D. First render of one large series (ms, median)', '')
    const names = Object.keys(D[0].runs[0])
    lines.push(`| variant | ${D.map((r) => `${r.config.points / 1000}k points`).join(' | ')} |`, `|---|${D.map(() => '---').join('|')}|`)
    for (const n of names) {
      lines.push(`| ${n} | ${D.map((r) => ms(median(r.runs.map((d) => d[n].median)))).join(' | ')} |`)
    }
    lines.push('')
  }
}

await writeFile(path.join(here, 'results', quick ? 'RESULTS.quick.md' : 'RESULTS.md'), lines.join('\n'))
console.log('wrote results')
